#!/usr/bin/env bash
# Convert Hotmart embed URL -> export file you can source
#
# Usage:
#   pbpaste | ./bin/hotmart-embed-to-exports.sh
#   ./bin/hotmart-embed-to-exports.sh 'https://cf-embed.play.hotmart.com/embed/...'
#   source exports/hotmart-exports.sh
#
# OUT=exports/parte03.sh pbpaste | ./bin/hotmart-embed-to-exports.sh

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${OUT:-$ROOT/exports/hotmart-exports.sh}"
mkdir -p "$(dirname "$OUT")"

URL="${1:-}"
if [[ -z "$URL" ]]; then
  if [[ ! -t 0 ]]; then
    URL="$(cat)"
  else
    echo "Paste embed URL, then Ctrl-D:" >&2
    URL="$(cat)"
  fi
fi

URL="$(printf '%s' "$URL" | tr -d '\r' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^["'\'']//' -e 's/["'\'']$//' )"

if [[ "$URL" != http*://* ]]; then
  echo "error: not a URL" >&2
  exit 1
fi

python3 - <<'PY' "$URL" | tee "$OUT"
import json, base64, sys
from urllib.parse import urlparse, parse_qs, unquote

url = sys.argv[1]
u = urlparse(url)
q = {k: v[0] for k, v in parse_qs(u.query, keep_blank_values=True).items()}

parts = [p for p in u.path.split("/") if p]
media = parts[-1] if parts else ""

jwt = q.get("jwtToken") or q.get("jwt") or ""
app = q.get("applicationCode") or ""
user_code = q.get("userCode") or ""
user_id = q.get("user") or q.get("userId") or ""
play_drm = None

if jwt.count(".") >= 2:
    payload = jwt.split(".")[1]
    payload += "=" * (-len(payload) % 4)
    try:
        data = json.loads(base64.urlsafe_b64decode(payload))
        media = data.get("mediaCode") or media
        user_id = str(data.get("userId") or user_id)
        user_code = data.get("userCode") or user_code
        play_drm = data.get("playDrm")
    except Exception as e:
        print(f"# warning: could not decode JWT: {e}", file=sys.stderr)

ref = ""
slug = "direito-cacd"
product_id = "2039476"
page_hash = ""
meta_raw = q.get("metadata")
if meta_raw:
    try:
        meta = json.loads(unquote(meta_raw))
        md = {m.get("key"): m.get("value") for m in meta if isinstance(m, dict)}
        slug = str(md.get("slug") or slug)
        product_id = str(md.get("productId") or product_id)
        page_hash = str(md.get("pageHash") or "")
    except Exception:
        pass

if page_hash:
    locale = q.get("locale") or "es"
    if locale in ("en",) or locale not in ("es", "pt", "pt-br"):
        locale = "es"
    ref = f"https://hotmart.com/{locale}/club/{slug}/products/{product_id}/content/{page_hash}"

def sh_escape(s: str) -> str:
    return "'" + s.replace("'", "'\"'\"'") + "'"

print("#!/usr/bin/env bash")
print("# generated by hotmart-embed-to-exports.sh — source this file")
print("# WARNING: contains secrets (JWT). Do not commit.")
print("unset EMBED embed")
print(f"export APP={sh_escape(app)}")
print(f"export USER_CODE={sh_escape(user_code)}")
print(f"export USER_ID={sh_escape(str(user_id))}")
print(f"export MEDIA={sh_escape(media)}")
print(f"export JWT={sh_escape(jwt)}")
if ref:
    print(f"export REF={sh_escape(ref)}")
else:
    print("export REF='https://hotmart.com/es/club/SLUG/products/PRODUCT/content/PAGE_HASH'")
    print("# WARNING: set REF manually")
print(f"export EMBED={sh_escape(url)}")
print()
print(f'echo "JWT length: ${{#JWT}} MEDIA=$MEDIA playDrm={play_drm}"')
print("# SECONDS_CLIP=5 ./bin/fast-hls-security-test.sh clip && open out/hls-security-test/sample-${SECONDS_CLIP:-5}s.mp4")
PY

chmod +x "$OUT"
echo "Wrote $OUT" >&2
echo "Load with:  source $OUT" >&2
